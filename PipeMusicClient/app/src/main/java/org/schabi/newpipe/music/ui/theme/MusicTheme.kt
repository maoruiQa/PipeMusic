@Composable
fun PipeMusicTheme(
    config: ThemeConfig,
    content: @Composable () -> Unit
) {
    val context = LocalContext.current
    val systemDark = isSystemInDarkTheme()
    val dark = when (config.darkMode) {
        1 -> false
        2 -> true
        else -> systemDark
    }
    val dynamic = config.dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S
    val colorScheme = remember(config, dark, dynamic) {
        ColorSchemeFactory.build(context, config, dark, dynamic)
    }

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (context as? Activity)?.window ?: return@SideEffect
            WindowCompat.getInsetsController(window, view).apply {
                isAppearanceLightStatusBars = !dark
                isAppearanceLightNavigationBars = !dark
            }
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = MusicTypography,
        shapes = MusicShapes,
        content = content
    )
}
